import { chromium } from "playwright-core";
const BASE = process.argv[2] || "http://localhost:3311", OUT = process.argv[3] || "/workspace/qa/saafi";
import fs from "fs"; fs.mkdirSync(OUT, { recursive: true });
const b = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox", "--enable-unsafe-swiftshader", "--use-angle=swiftshader"] });
let fail = 0; const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fail++; };
for (const [w, h] of [[360, 780], [390, 844], [1440, 900]]) {
  const ctx = await b.newContext({ viewport: { width: w, height: h }, deviceScaleFactor: w < 800 ? 2 : 1, hasTouch: w < 800, isMobile: w < 800 });
  const p = await ctx.newPage(); const errs = []; p.on("pageerror", e => errs.push(e.message));
  await p.goto(BASE + "/c/saafi"); await p.waitForSelector("canvas", { timeout: 20000 }); await p.waitForTimeout(1500);
  const totalSel = w < 1024 ? ".mobile-bar strong" : ".summary .total";
  const tot = async () => (await p.locator(totalSel).innerText()).replace(/\D/g, "");
  ok(await p.locator("h1").innerText().then(t => t.includes("Cleaning Estimator: Price your home cleaning")), `${w} title`);
  ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${w} no sideways scroll`);
  await p.screenshot({ path: `${OUT}/${w}-top.png` });
  const t0 = await tot();
  await p.locator("#area").fill("4000"); await p.waitForTimeout(600); const t1 = await tot(); ok(+t1 > +t0, `${w} slider raises price ${t0}->${t1}`);
  await p.getByRole("group", { name: "Floors" }).getByRole("button", { name: "3" }).click();
  await p.getByRole("button", { name: "More bedrooms" }).click();
  await p.getByRole("button", { name: "More bathrooms" }).click();
  ok((await p.locator(".home-label").innerText()).includes("A 3 floor home: 4,000 sq ft, 4 bed, 3 bath"), `${w} label updates`);
  await p.locator("label.type", { hasText: "Deep" }).click(); await p.waitForTimeout(600);
  const t2 = await tot(); ok(+t2 > +t1, `${w} deep raises price ${t1}->${t2}`);
  ok((await p.locator(".summary").innerText()).includes("Stairs and extra floors"), `${w} breakdown has floors`);
  await p.getByRole("button", { name: "Open floors" }).click(); await p.getByRole("button", { name: "Roof" }).click();
  ok(await p.getByRole("button", { name: "Roof" }).getAttribute("aria-pressed") === "true", `${w} roof toggle`);
  await p.getByRole("button", { name: "sq m" }).click(); ok((await p.locator(".big-value").innerText()).includes("sq m"), `${w} sq m switch`);
  await p.getByRole("button", { name: "sq ft", exact: true }).click();
  await p.locator(".model").scrollIntoViewIfNeeded(); await p.waitForTimeout(1200);
  await p.screenshot({ path: `${OUT}/${w}-model.png` });
  await p.screenshot({ path: `${OUT}/${w}-full.png`, fullPage: true });
  const book = w < 1024 ? p.locator(".mobile-bar .cta") : p.locator(".summary .cta");
  await book.click(); await p.waitForSelector("[role=dialog]");
  ok((await p.locator("[role=dialog]").innerText()).includes("Pick a day and tell us where to go."), `${w} modal opens`);
  await p.getByRole("button", { name: "Send booking on WhatsApp" }).click();
  ok(await p.locator(".in em").count() >= 3, `${w} empty submit shows errors`);
  await p.getByLabel("Full name").fill("Omar Khalid"); await p.getByLabel("Phone").fill("050 123 4567");
  await p.getByLabel("Address").fill("Villa 12, Al Barsha 2, Dubai"); await p.getByLabel("Notes for the crew").fill("Gate code 4411");
  await p.screenshot({ path: `${OUT}/${w}-modal.png` });
  ok(await p.evaluate(() => { const m = document.querySelector(".modal").getBoundingClientRect(); return [...document.querySelectorAll(".modal input,.modal textarea")].every(e => e.getBoundingClientRect().right <= m.right - 8); }), `${w} modal fields fit`);
  const [pop] = await Promise.all([ctx.waitForEvent("page", { timeout: 8000 }).catch(() => null), p.getByRole("button", { name: "Send booking on WhatsApp" }).click()]);
  const url = pop ? pop.url() : ""; const txt = url ? (new URL(url).searchParams.get("text") || "") : "";
  ok(url.includes("wa.me") || url.includes("whatsapp"), `${w} WhatsApp opens (${url.slice(0, 40)})`);
  ok(txt.includes("Omar Khalid") && txt.includes("Gate code 4411") && txt.includes("A 3 floor home"), `${w} summary prefilled`);
  if (pop) await pop.close();
  await p.keyboard.press("Escape"); ok(await p.locator("[role=dialog]").count() === 0, `${w} Escape closes modal`);
  ok(errs.length === 0, `${w} no page errors ${errs.join("|")}`);
  await ctx.close();
}
await b.close(); console.log(fail ? `${fail} FAILED` : "ALL PASS"); process.exit(fail ? 1 : 0);
